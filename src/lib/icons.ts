/**
 * Icon registry.
 *
 * Records store an icon *name* rather than an imported component, because the
 * value comes from the database and a component cannot be serialised. The
 * registry is the only place the mapping exists, and an unknown name falls
 * back to a neutral glyph instead of rendering nothing.
 */
