  activity: Activity,
  award: Award,
  banknote: Banknote,
  "book-open": BookOpen,
  briefcase: Briefcase,
  building: Building2,
  calendar: Calendar,
  car: Car,
  "check-circle": CheckCircle2,
  circle: Circle,
